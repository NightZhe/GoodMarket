-- 5. 內部：新增（只給 service_role；Edge Function bank-account-add 呼叫）
-- ═══════════════════════════════════════════════════════════════════════
-- 資料庫是最後一道。檢查順序：NOT_AUTHENTICATED → BANK_CODE → BRANCH_CODE → ACCOUNT_NUMBER（末四碼／fingerprint 格式）→ ACCOUNT_HOLDER
--   → （鎖）→ BANK_ACCOUNT_LIMIT → BANK_ACCOUNT_DUPLICATE（同人）→ PHONE_REQUIRED → STEP_UP_REQUIRED（後兩者只在已有 ≥1 筆時）→ BANK_ACCOUNT_TAKEN（他人）
create or replace function public._add_bank_account(
  p_user        uuid,
  p_bank_code   text,
  p_branch_code text,
  p_cipher      text,
  p_key_version smallint,
  p_fingerprint text,
  p_last4       text,
  p_holder      text,
  p_set_payout  boolean,
  p_otp_at      timestamptz
) returns jsonb language plpgsql volatile security definer set search_path = public as $$
declare
  v_branch text := nullif(public._rv_trim(coalesce(p_branch_code, '')), '');
  v_holder text := public._rv_trim(coalesce(p_holder, ''));
  v_count  int;
  v_payout boolean;
  v_id     uuid;
begin
  if p_user is null or not exists (select 1 from auth.users u where u.id = p_user) then
    perform public._bank_err('NOT_AUTHENTICATED');
  end if;
  if p_bank_code is null or not exists (select 1 from public.bank_codes c where c.code = p_bank_code) then
    perform public._bank_err('BANK_CODE_INVALID');
  end if;
  if v_branch is null or v_branch !~ '^[0-9]{4}$' or not exists (
       select 1 from public.bank_branches b where b.bank_code = p_bank_code and b.branch_code = v_branch) then
    perform public._bank_err('BRANCH_CODE_INVALID');
  end if;
  if p_last4 is null or p_last4 !~ '^[0-9]{4}$' or p_fingerprint is null or p_fingerprint !~ '^[0-9a-f]{64}$' then
    perform public._bank_err('ACCOUNT_NUMBER_INVALID');
  end if;
  if char_length(v_holder) not between 1 and 50 or v_holder ~ '[\x01-\x1f\x7f-\x9f]' then
    perform public._bank_err('ACCOUNT_HOLDER_INVALID');
  end if;
  if p_cipher is null or p_cipher = '' or p_key_version is null then
    perform public._bank_err('INTERNAL');
  end if;

  perform public._bank_lock(p_user);
  select count(*) into v_count from public.bank_accounts a where a.user_id = p_user;
  if v_count >= 5 then perform public._bank_err('BANK_ACCOUNT_LIMIT'); end if;
  if exists (select 1 from public.bank_accounts a where a.user_id = p_user and a.bank_code = p_bank_code and a.account_fingerprint = p_fingerprint) then
    perform public._bank_err('BANK_ACCOUNT_DUPLICATE');
  end if;
  if v_count >= 1 then
    if not public._bank_has_phone(p_user) then perform public._bank_err('PHONE_REQUIRED'); end if;
    if not public._bank_otp_fresh(p_otp_at) then perform public._bank_err('STEP_UP_REQUIRED'); end if;
  end if;
  -- TAKEN 放在簡訊檢查之後：已有帳號的人沒通過簡訊就不能探測某個帳號是否被別人占用（第一筆仍可探測，見回報）
  if exists (select 1 from public.bank_accounts a where a.bank_code = p_bank_code and a.account_fingerprint = p_fingerprint) then
    perform public._bank_err('BANK_ACCOUNT_TAKEN');
  end if;

  v_payout := v_count = 0 or coalesce(p_set_payout, false);
  if v_payout and v_count > 0 then
    update public.bank_accounts set is_payout = false, payout_since = null, updated_at = now()
     where user_id = p_user and is_payout;                                      -- N3：舊撥款帳號立即變一般
  end if;
  begin
    insert into public.bank_accounts (user_id, bank_code, branch_code, account_cipher, key_version, account_fingerprint,
                                      account_last4, account_holder, is_payout, payout_since)
    values (p_user, p_bank_code, v_branch, p_cipher, p_key_version, p_fingerprint, p_last4, v_holder,
            v_payout, case when v_payout then now() end)
    returning id into v_id;
  exception when unique_violation then
    -- 另一個人同時綁了同一個帳號（跨人沒有共用的鎖，由唯一限制擋下）
    perform public._bank_err('BANK_ACCOUNT_TAKEN');
  end;
  insert into public.bank_account_events (user_id, account_id, actor, action, bank_code, account_last4, status, is_payout, step_up)
  values (p_user, v_id, p_user, 'add', p_bank_code, p_last4, 'pending', v_payout, v_count >= 1);
  return public._bank_accounts_json(p_user) || jsonb_build_object('id', v_id);
end $$;
revoke all on function public._add_bank_account(uuid, text, text, text, smallint, text, text, text, boolean, timestamptz) from public, anon, authenticated;
grant execute on function public._add_bank_account(uuid, text, text, text, smallint, text, text, text, boolean, timestamptz) to service_role;

