-- 銀行帳號（掛人、最多 5 筆、不可修改）：介面契約 .work/seller-bank-account/interface-bank-account-v2.md（v2.1）；工單 T-B2
--
-- 只做相容的新增：五張新表（bank_codes、bank_branches、bank_accounts、bank_account_events、bank_ui_settings）
-- 與一組函式。不動任何既有的表、欄位、權限、函式；特別是 seller_ecpay_merchants、submit_seller_ecpay_merchant、
-- get_shops_online_payable、place_online_order 一律不碰（AC-37、AC-50）。
-- 只依賴更早就存在的 _acct_uid()、_rv_raise()、_rv_trim()、shops、auth.users。可重複執行。
--
-- 安全邊界：
--   · 表對 anon、authenticated、PUBLIC 都零權限（連 select 都沒有），RLS 開著且不建 policy。
--   · 寫入只走 Edge Function bank-account-add（AES-256-GCM 加密後）→ _add_bank_account（只給 service_role）。
--     資料庫只存密文 account_cipher；本檔沒有任何解密路徑。
--   · 事件紀錄表不放完整帳號、密文、fingerprint（只有銀行代碼、末四碼）。
--   · 同一個銀行帳號全站只能一個人綁（決策 T2）：account_fingerprint 不含 userId，unique (bank_code, account_fingerprint)。
--   · bank_accounts／bank_account_events 掛 auth.users on delete cascade（刪帳號一併消失）。
--
-- 錯誤格式（契約 §3）：raise exception '<中文說明>' using hint = '<錯誤碼>'（同 _rv_raise）。

