-- 1. 資料表
-- ═══════════════════════════════════════════════════════════════════════
create table if not exists public.bank_codes (
  code text primary key,
  name text not null,
  constraint bank_codes_code_valid check (code ~ '^[0-9]{3}$'),
  constraint bank_codes_name_valid check (char_length(name) between 1 and 100)
);

create table if not exists public.bank_branches (
  bank_code   text not null references public.bank_codes(code) on delete cascade,
  branch_code text not null,
  name        text not null,
  city        text not null,
  primary key (bank_code, branch_code),
  constraint bank_branches_code_valid check (branch_code ~ '^[0-9]{4}$'),
  constraint bank_branches_name_valid check (char_length(name) between 1 and 100),
  constraint bank_branches_city_valid check (city in (
    '臺北市','基隆市','新北市','桃園市','新竹市','新竹縣','苗栗縣','臺中市','彰化縣','南投縣','雲林縣',
    '嘉義市','嘉義縣','臺南市','高雄市','屏東縣','宜蘭縣','花蓮縣','臺東縣','澎湖縣','金門縣','連江縣'))
);

-- account_cipher＝base64(iv ‖ ciphertext ‖ tag)，金鑰在 Edge Function 的 secret，不在資料庫。
-- account_fingerprint＝hex(HMAC-SHA256(fpKey, bankCode|account))：不含 userId，所以全站同一個帳號有同一個值（T2）。
create table if not exists public.bank_accounts (
  id                  uuid primary key default gen_random_uuid(),
  user_id             uuid not null references auth.users(id) on delete cascade,
  bank_code           text not null references public.bank_codes(code),
  branch_code         text not null,
  account_cipher      text not null,
  key_version         smallint not null,
  account_fingerprint text not null,
  account_last4       text not null,
  account_holder      text not null,
  status              text not null default 'pending',
  reason              text null,
  is_payout           boolean not null default false,
  payout_since        timestamptz null,
  verified_at         timestamptz null,
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now(),
  constraint bank_accounts_branch_fk foreign key (bank_code, branch_code) references public.bank_branches(bank_code, branch_code),
  constraint bank_accounts_last4_valid check (account_last4 ~ '^[0-9]{4}$'),
  constraint bank_accounts_fp_valid check (account_fingerprint ~ '^[0-9a-f]{64}$'),
  constraint bank_accounts_holder_valid check (char_length(account_holder) between 1 and 50 and account_holder !~ '[\x01-\x1f\x7f-\x9f]'),
  constraint bank_accounts_cipher_valid check (char_length(account_cipher) > 0),
  constraint bank_accounts_status_valid check (status in ('pending', 'verified', 'rejected')),
  constraint bank_accounts_reason_valid check ((status = 'rejected') = (reason is not null)),
  constraint bank_accounts_payout_not_rejected check (not (is_payout and status = 'rejected')),
  constraint bank_accounts_payout_since_valid check (is_payout = (payout_since is not null)),
  constraint bank_accounts_verified_at_valid check ((status = 'verified') = (verified_at is not null)),
  constraint bank_accounts_fp_unique unique (bank_code, account_fingerprint)      -- T2：全站唯一
);
create unique index if not exists bank_accounts_one_payout_per_user on public.bank_accounts (user_id) where is_payout;
create index if not exists bank_accounts_user_idx on public.bank_accounts (user_id, created_at);

create table if not exists public.bank_account_events (
  id            bigint generated always as identity primary key,
  user_id       uuid not null references auth.users(id) on delete cascade,
  account_id    uuid null,                      -- 不設外鍵：帳號被刪後事件仍在
  actor         uuid null,                      -- 做事的人；維運／系統＝null
  action        text not null,
  bank_code     text null,
  account_last4 text null,
  status        text null,
  reason        text null,
  is_payout     boolean null,                   -- 動作之後是否為撥款帳號
  step_up       boolean not null default false, -- 這次動作是否通過簡訊再驗證
  at            timestamptz not null default now(),
  constraint bank_account_events_action_valid check (action in ('add', 'delete', 'set_payout', 'status')),
  constraint bank_account_events_last4_valid check (account_last4 is null or account_last4 ~ '^[0-9]{4}$')
);
create index if not exists bank_account_events_user_idx on public.bank_account_events (user_id, at);

-- 單列設定（T3：logo 伺服器端開關。改這一列即生效，App 不必重送審）
create table if not exists public.bank_ui_settings (
  id           boolean primary key default true,
  logos_enabled boolean not null default true,
  updated_at   timestamptz not null default now(),
  constraint bank_ui_settings_single check (id)
);
insert into public.bank_ui_settings (id, logos_enabled) values (true, true) on conflict (id) do nothing;

