-- 錯誤碼 → 中文說明；hint＝錯誤碼（契約 §3：message 給人看、hint 給程式）
create or replace function public._bank_err(p_code text)
returns void language plpgsql stable set search_path = public as $$
begin
  perform public._rv_raise(p_code, case p_code
    when 'NOT_AUTHENTICATED'            then '請先登入'
    when 'BANK_CODE_INVALID'            then '請選擇銀行'
    when 'BRANCH_CODE_INVALID'          then '請選擇分行'
    when 'ACCOUNT_NUMBER_INVALID'       then '帳號需為 8 到 16 位數字'
    when 'ACCOUNT_HOLDER_INVALID'       then '戶名需為 1 到 50 個字，且不能含換行'
    when 'BANK_ACCOUNT_LIMIT'           then '銀行帳號最多只能存 5 個，請先刪除不用的'
    when 'BANK_ACCOUNT_DUPLICATE'       then '這個銀行帳號你已經綁過了'
    when 'BANK_ACCOUNT_TAKEN'           then '這個銀行帳號已經被其他帳號綁定'
    when 'BANK_ACCOUNT_NOT_FOUND'       then '找不到這個銀行帳號'
    when 'BANK_ACCOUNT_REJECTED'        then '未通過的銀行帳號不能設為撥款帳號'
    when 'PAYOUT_ACCOUNT_CANNOT_DELETE' then '這是撥款帳號，要先把別的帳號設為撥款帳號才能刪除'
