revoke all on function public._bank_err(text) from public, anon, authenticated;

-- 簡訊再驗證是否新鮮：now()-10 分鐘 ≤ 時間 ≤ now()+1 分鐘
create or replace function public._bank_otp_fresh(p_at timestamptz)
returns boolean language sql stable set search_path = public as $$
  select p_at is not null and p_at >= now() - interval '10 minutes' and p_at <= now() + interval '1 minute';
$$;
revoke all on function public._bank_otp_fresh(timestamptz) from public, anon, authenticated;

-- 目前 JWT 的 amr 中 method='otp' 的最大 timestamp。amr 不是陣列或元素壞掉一律當作沒有（CASE 保證判斷順序）。
create or replace function public._bank_jwt_otp_at()
returns timestamptz language sql stable set search_path = public as $$
  select to_timestamp(max(case when jsonb_typeof(e) = 'object' and e->>'method' = 'otp'
                                and (e->>'timestamp') ~ '^[0-9]{1,12}$' then (e->>'timestamp')::bigint end))
  from jsonb_array_elements(case when jsonb_typeof(auth.jwt()->'amr') = 'array' then auth.jwt()->'amr' else '[]'::jsonb end) e;
$$;
revoke all on function public._bank_jwt_otp_at() from public, anon, authenticated;

