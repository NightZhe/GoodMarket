-- 設為撥款帳號（簡訊再驗證由資料庫讀 auth.jwt()->'amr'）。順序：登入→鎖→找得到→已是撥款帳號就回→未通過→手機→簡訊
create or replace function public.set_payout_bank_account(p_id uuid)
returns jsonb language plpgsql volatile security definer set search_path = public as $$
declare
  v_uid uuid := public._acct_uid();
  v_row public.bank_accounts;
begin
  perform public._bank_lock(v_uid);
  select * into v_row from public.bank_accounts a where a.id = p_id and a.user_id = v_uid for update;
  if not found then perform public._bank_err('BANK_ACCOUNT_NOT_FOUND'); end if;
  if v_row.is_payout then return public._bank_accounts_json(v_uid); end if;   -- 冪等：不要求簡訊、不寫事件
  if v_row.status = 'rejected' then perform public._bank_err('BANK_ACCOUNT_REJECTED'); end if;
  if not public._bank_has_phone(v_uid) then perform public._bank_err('PHONE_REQUIRED'); end if;
  if not public._bank_otp_fresh(public._bank_jwt_otp_at()) then perform public._bank_err('STEP_UP_REQUIRED'); end if;
  update public.bank_accounts set is_payout = false, payout_since = null, updated_at = now()
   where user_id = v_uid and is_payout;                                         -- 先卸舊的，再設新的（避開唯一索引瞬間衝突）
  update public.bank_accounts set is_payout = true, payout_since = now(), updated_at = now() where id = v_row.id;
  insert into public.bank_account_events (user_id, account_id, actor, action, bank_code, account_last4, status, reason, is_payout, step_up)
  values (v_uid, v_row.id, v_uid, 'set_payout', v_row.bank_code, v_row.account_last4, v_row.status, v_row.reason, true, true);
  return public._bank_accounts_json(v_uid);
end $$;
revoke all on function public.set_payout_bank_account(uuid) from public;
grant execute on function public.set_payout_bank_account(uuid) to anon, authenticated;

