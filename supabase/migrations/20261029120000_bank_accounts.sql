-- 前端看的列表（契約 §3.1）：沒有 user_id、密文、金鑰版本、fingerprint、完整帳號
create or replace function public._bank_accounts_json(p_user uuid)
returns jsonb language sql stable security definer set search_path = public as $$
  select jsonb_build_object('limit', 5, 'accounts', coalesce(jsonb_agg(
    jsonb_build_object(
      'id', a.id, 'bank_code', a.bank_code, 'bank_name', b.name,
      'branch_code', a.branch_code, 'branch_name', br.name, 'branch_city', br.city,
      'last4', a.account_last4, 'holder', a.account_holder,
      'status', a.status, 'reason', a.reason,
      'is_payout', a.is_payout, 'payout_since', a.payout_since,
      'verified_at', a.verified_at, 'created_at', a.created_at)
    order by a.is_payout desc, a.created_at, a.id), '[]'::jsonb))
  from public.bank_accounts a
  join public.bank_codes b on b.code = a.bank_code
  join public.bank_branches br on br.bank_code = a.bank_code and br.branch_code = a.branch_code
  where a.user_id = p_user;
$$;
revoke all on function public._bank_accounts_json(uuid) from public, anon, authenticated;

