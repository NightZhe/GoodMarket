-- 7. 給 PR-乙：「有沒有撥款帳號」（N4：待驗證或已驗證都算，未通過不算）
-- ═══════════════════════════════════════════════════════════════════════
-- 規則只寫在 _user_has_payout_account 一處；三處（get_shops_online_payable、place_online_order、pay_begin_attempt）都呼叫 _shop_has_payout_account。
-- 只給 service_role（否則任何人能探測別人有沒有綁）；security definer 的呼叫端以擁有者身分執行得到。
create or replace function public._user_has_payout_account(p_user uuid)
returns boolean language sql stable security definer set search_path = public as $$
  select p_user is not null and exists (
    select 1 from public.bank_accounts a where a.user_id = p_user and a.is_payout and a.status in ('pending', 'verified'));
$$;
create or replace function public._shop_has_payout_account(p_shop_id uuid)
returns boolean language sql stable security definer set search_path = public as $$
  select coalesce((select public._user_has_payout_account(s.owner_id) from public.shops s where s.id = p_shop_id), false);
$$;
revoke all on function public._user_has_payout_account(uuid) from public, anon, authenticated;
revoke all on function public._shop_has_payout_account(uuid) from public, anon, authenticated;
grant execute on function public._user_has_payout_account(uuid) to service_role;
grant execute on function public._shop_has_payout_account(uuid) to service_role;
