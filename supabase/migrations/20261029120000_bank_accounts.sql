-- 6. 維運（只給 service_role／postgres）
-- ═══════════════════════════════════════════════════════════════════════
--   npx supabase db query --linked "select public.admin_set_bank_account_status('<account id>', 'verified');"
--   N5：任何狀態可轉任何狀態。rejected 必須有 reason；其他狀態清掉 reason。verified 寫 verified_at，其他清掉。
--   標 rejected 的撥款帳號同時卸掉撥款身分（此人變成沒有撥款帳號，不自動遞補）。
create or replace function public.admin_set_bank_account_status(p_account uuid, p_status text, p_reason text default null)
returns jsonb language plpgsql volatile security definer set search_path = public as $$
declare
  v_reason text := nullif(public._rv_trim(coalesce(p_reason, '')), '');
  v_row    public.bank_accounts;
begin
  if p_status is null or p_status not in ('pending', 'verified', 'rejected') then
    perform public._bank_err('STATUS_INVALID');
  end if;
  if p_status = 'rejected' and v_reason is null then perform public._bank_err('REASON_REQUIRED'); end if;
  if p_status <> 'rejected' then v_reason := null; end if;
  select * into v_row from public.bank_accounts a where a.id = p_account;
  if not found then perform public._bank_err('BANK_ACCOUNT_NOT_FOUND'); end if;
  perform public._bank_lock(v_row.user_id);
  update public.bank_accounts a
     set status = p_status, reason = v_reason, updated_at = now(),
         verified_at = case when p_status = 'verified' then now() else null end,
         is_payout = a.is_payout and p_status <> 'rejected',
         payout_since = case when a.is_payout and p_status <> 'rejected' then a.payout_since end
   where a.id = p_account
  returning * into v_row;
  if not found then perform public._bank_err('BANK_ACCOUNT_NOT_FOUND'); end if;
  insert into public.bank_account_events (user_id, account_id, actor, action, bank_code, account_last4, status, reason, is_payout)
  values (v_row.user_id, v_row.id, null, 'status', v_row.bank_code, v_row.account_last4, p_status, v_reason, v_row.is_payout);
  return jsonb_build_object('user_id', v_row.user_id, 'id', v_row.id, 'bank_code', v_row.bank_code, 'last4', v_row.account_last4,
                            'status', v_row.status, 'reason', v_row.reason, 'is_payout', v_row.is_payout,
                            'payout_since', v_row.payout_since, 'verified_at', v_row.verified_at);
end $$;
revoke all on function public.admin_set_bank_account_status(uuid, text, text) from public, anon, authenticated;
grant execute on function public.admin_set_bank_account_status(uuid, text, text) to service_role;

