create or replace function public._bank_limit_guard()
returns trigger language plpgsql set search_path = public as $$
begin
  perform public._bank_lock(new.user_id);
  if (select count(*) from public.bank_accounts a where a.user_id = new.user_id) >= 5 then
    perform public._bank_err('BANK_ACCOUNT_LIMIT');
